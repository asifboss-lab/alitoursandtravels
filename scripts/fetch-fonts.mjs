/**
 * Self-hosts the two web fonts the site uses.
 *
 * Fonts are vendored rather than loaded from a third-party CDN so the site makes
 * no external requests on page load (better privacy and no layout shift), and so
 * it still works if the visitor is on a restricted network.
 *
 * Run with: node scripts/fetch-fonts.mjs
 */
import { mkdir, writeFile } from 'node:fs/promises';
import path from 'node:path';

const CSS_URL =
  'https://fonts.googleapis.com/css2?family=Sora:wght@500;600;700&family=Inter:wght@400;500;600&display=swap';
// A modern desktop UA is required for Google to serve woff2 rather than ttf.
const UA =
  'Mozilla/5.0 (X11; Linux x86_64) AppleWebKit/537.36 (KHTML, like Gecko) Chrome/120.0.0.0 Safari/537.36';
const OUT_DIR = path.resolve('public/fonts');
const CSS_OUT = path.resolve('src/styles/fonts.css');
const KEEP = new Set(['latin', 'latin-ext']);

async function main() {
  await mkdir(OUT_DIR, { recursive: true });
  await mkdir(path.dirname(CSS_OUT), { recursive: true });

  const res = await fetch(CSS_URL, { headers: { 'User-Agent': UA } });
  if (!res.ok) throw new Error(`Google Fonts CSS: HTTP ${res.status}`);
  const css = await res.text();

  // Blocks look like: /* latin */ @font-face { ... src: url(...) format('woff2'); ... }
  const blocks = css.match(/\/\*[\s\S]*?\*\/\s*@font-face\s*\{[\s\S]*?\}/g) ?? [];
  const rules = [];
  const fileByUrl = new Map();

  for (const block of blocks) {
    const subset = block.match(/\/\*\s*([\w-]+)\s*\*\//)?.[1];
    if (!subset || !KEEP.has(subset)) continue;

    const family = block.match(/font-family:\s*'([^']+)'/)?.[1];
    const weight = block.match(/font-weight:\s*(\d+)/)?.[1];
    const unicodeRange = block.match(/unicode-range:\s*([^;]+);/)?.[1];
    const url = block.match(/url\((https:[^)]+\.woff2)\)/)?.[1];
    if (!family || !weight || !url) continue;

    // Google serves one variable-font file that many weights share, so files are
    // de-duplicated by URL while every weight still gets its own @font-face rule.
    if (!fileByUrl.has(url)) {
      const slug = `${family.toLowerCase()}-${subset}`;
      const bin = await fetch(url, { headers: { 'User-Agent': UA } });
      if (!bin.ok) throw new Error(`font download ${url}: HTTP ${bin.status}`);
      await writeFile(path.join(OUT_DIR, `${slug}.woff2`), Buffer.from(await bin.arrayBuffer()));
      fileByUrl.set(url, slug);
      console.log(`saved ${slug}.woff2`);
    }

    rules.push(
      `@font-face {\n` +
        `  font-family: '${family}';\n` +
        `  font-style: normal;\n` +
        `  font-weight: ${weight};\n` +
        `  font-display: swap;\n` +
        `  src: url('/fonts/${fileByUrl.get(url)}.woff2') format('woff2');\n` +
        (unicodeRange ? `  unicode-range: ${unicodeRange};\n` : '') +
        `}`,
    );
    console.log(`  rule ${family} ${weight} ${subset}`);
  }

  if (!rules.length) throw new Error('No font files were resolved from the Google Fonts CSS.');
  await writeFile(
    CSS_OUT,
    `/* Generated by scripts/fetch-fonts.mjs - do not edit by hand. */\n${rules.join('\n\n')}\n`,
    'utf8',
  );
  console.log(`\nWrote ${rules.length} @font-face rules (${fileByUrl.size} files) to ${CSS_OUT}`);
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
